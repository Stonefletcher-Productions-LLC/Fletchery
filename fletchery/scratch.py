"""Retention for scratch folders Fletchery did not create (2026-11-16: eight sessions building side by side left
SF-NODE-01's E: at 0 GB and the PC under its disk guard; storage.py only knows Fletchery's own task and merge copies).

People and agent sessions make their own worktrees, clones and packaged builds beside Fletchery's. Each Unreal one holds
6-15 GB of build output nobody comes back for. For every folder directly under a configured scratch root, and every checkout one level down inside a plain grouping
folder, this module:

  * trims  regenerable Unreal output (Intermediate, Binaries, DerivedDataCache, Saved/Cooked, ...) once the folder has
           been idle `trim_hours` (2 h when the drive is short). Only folders git ignores and tracks nothing in.
  * removes a git worktree idle `remove_days` whose work is provably elsewhere: clean status, HEAD contained in a remote
           branch, not locked, no other worktree inside it, nothing unique among its ignored files. `git worktree remove`
           without --force, so git refuses too if anything changed meanwhile. The branch stays. Never prunes.
  * removes a plain folder matching a `disposable` pattern (packaged builds) idle `remove_days`.
  * keeps   everything else and says why; the kept folders with uncommitted or unpushed work are the list for a person.

Nothing a process names on its command line is touched, nor anything matching `keep`, nor a link. Clones (their own
.git folder) are only ever trimmed. Python standard library only: the node worker loads this file from beside itself.

    python scratch.py --root E:\\lifeshare-scratch --keep LifeShareArt --mode remove            what a pass would do
    python scratch.py --root E:\\lifeshare-scratch --keep LifeShareArt --mode remove --apply    do it
"""
from __future__ import annotations

import fnmatch
import json
import os
from pathlib import Path
import re
import shutil
import stat
import subprocess
import sys
import time

MODES = ("off", "report", "trim", "remove")
# Regenerated by the next build, cook or editor start. Saved/Logs, screenshots and captures are not in this list.
TRIM_DIRS = ("Intermediate", "Binaries", "DerivedDataCache", "Saved/Cooked", "Saved/StagedBuilds",
             "Saved/ShaderDebugInfo")
# Ignored files under these are dropped with a removed worktree (the newest Saved/Logs are copied out first).
DROP_IGNORED = ("Saved", ".vs", ".idea", "__pycache__")
URGENT_TRIM_HOURS = 2.0
LOG_BACKUP_BYTES = 50 * 1024 ** 2
GIT_TIMEOUT = 300


def _now_iso() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _reparse(path: Path) -> bool:
    info = path.lstat()
    return stat.S_ISLNK(info.st_mode) or bool(getattr(info, "st_file_attributes", 0) & 0x400)


def _long(path) -> str:
    spelled = str(path)
    return "\\\\?\\" + spelled if os.name == "nt" and not spelled.startswith("\\\\?\\") else spelled


def _remove_tree(target: Path) -> None:
    def writable(func, name, _exc):
        os.chmod(name, stat.S_IWRITE)
        func(name)
    shutil.rmtree(_long(target), onerror=writable)


def _quick_size(path: Path) -> int:
    total, stack = 0, [path]
    while stack:
        try:
            with os.scandir(stack.pop()) as entries:
                for entry in entries:
                    if entry.is_symlink():
                        continue
                    if entry.is_dir(follow_symlinks=False):
                        stack.append(Path(entry.path))
                    elif entry.is_file(follow_symlinks=False):
                        total += entry.stat(follow_symlinks=False).st_size
        except OSError:
            continue
    return total


def _has_links(path: Path) -> bool:
    """A junction or symlink anywhere inside: deleting through one would reach files that live elsewhere."""
    stack = [path]
    while stack:
        with os.scandir(stack.pop()) as entries:
            for entry in entries:
                info = entry.stat(follow_symlinks=False)
                if entry.is_symlink() or getattr(info, "st_file_attributes", 0) & 0x400:
                    return True
                if entry.is_dir(follow_symlinks=False):
                    stack.append(Path(entry.path))
    return False


def _shallow_newest(path: Path, depth: int = 3) -> float:
    """Latest change near the top of a folder, ignoring .git (git status rewrites its index)."""
    newest, stack = path.stat().st_mtime, [(path, 0)]
    while stack:
        directory, level = stack.pop()
        try:
            with os.scandir(directory) as entries:
                for entry in entries:
                    if entry.name == ".git":
                        continue
                    info = entry.stat(follow_symlinks=False)
                    newest = max(newest, info.st_mtime)
                    if level + 1 < depth and entry.is_dir(follow_symlinks=False) and not entry.is_symlink():
                        stack.append((Path(entry.path), level + 1))
        except OSError:
            continue
    return newest


def _git_exe() -> str:
    """git, also where it is installed but not on PATH (SF-NODE-01's PowerShell, 2026-11-16)."""
    found = os.environ.get("FLETCHERY_GIT") or shutil.which("git")
    if not found and os.name == "nt":
        for base in (os.environ.get("ProgramFiles"), os.environ.get("ProgramFiles(x86)"), os.environ.get("LOCALAPPDATA")):
            for tail in (r"Git\cmd\git.exe", r"Programs\Git\cmd\git.exe"):
                if base and Path(base, tail).is_file():
                    return str(Path(base, tail))
    return found or "git"


def _git(cwd: Path, *args: str) -> str:
    try:
        done = subprocess.run([_git_exe(), "-c", "core.longpaths=true", *args], cwd=str(cwd), capture_output=True, text=True,
                              encoding="utf-8", errors="replace", timeout=GIT_TIMEOUT,
                              creationflags=0x08000000 if os.name == "nt" else 0)
    except (OSError, subprocess.SubprocessError) as exc:
        raise RuntimeError(f"git {args[0]} did not run: {exc}") from exc
    if done.returncode:
        raise RuntimeError(f"git {' '.join(args[:2])} failed: {(done.stderr or done.stdout).strip()[:300]}")
    return done.stdout.rstrip("\r\n")


# Programs that do the work in scratch folders. If one is running and Windows will not show its command line (it
# belongs to another account or session), the pass cannot tell which folder it uses, so the pass touches nothing.
WORK_PROGRAMS = {"powershell.exe", "pwsh.exe", "cmd.exe", "python.exe", "pythonw.exe", "py.exe", "node.exe", "git.exe",
                 "bash.exe", "sh.exe", "dotnet.exe", "cl.exe", "link.exe", "msbuild.exe", "blender.exe", "claude.exe"}
WORK_PREFIXES = ("unreal", "shadercompile", "ue4", "ue5")
SIBLING_SUFFIXES = ("logs", "log", "out", "output", "results", "result", "captures", "capture")


def readable_lines(rows: list[tuple[int, str, str]], own_pid: int | None = None) -> list[str]:
    """Command lines (forward slashes, lower case) from (pid, image name, command line) rows. Raises unless the list
    is provably whole: on SF-NODE-01 (2026-11-17) the worker's scheduled task saw no command line for two running
    jobs, read that as "nothing running", and trimmed the build output of both live worktrees."""
    hidden, lines, own_seen = [], [], own_pid is None
    for pid, name, command in rows:
        command = (command or "").strip()
        if pid == own_pid:
            own_seen = bool(command)
        if command:
            lines.append(command.replace("\\", "/").lower())
        elif name.lower() in WORK_PROGRAMS or name.lower().startswith(WORK_PREFIXES):
            hidden.append(name)
    if not own_seen:
        raise RuntimeError("Cannot list running processes: this pass's own process is missing from the list")
    if hidden:
        names = ", ".join(sorted(set(hidden))[:6])
        raise RuntimeError(f"Cannot read the command line of {len(hidden)} running program(s) ({names}); "
                           "run the cleanup as the account that runs the jobs")
    return lines


def command_lines() -> list[str]:
    """Every process's command line, forward slashes, lower case. Raises when Windows cannot be asked or the answer
    is not whole (readable_lines): a pass that cannot see who is running touches nothing."""
    if os.name != "nt":
        lines = []
        for proc in Path("/proc").glob("[0-9]*/cmdline"):
            try:
                if int(proc.parent.name) != os.getpid():
                    lines.append(proc.read_bytes().replace(b"\0", b" ").decode("utf-8", "replace").lower())
            except (OSError, ValueError):
                continue
        return lines
    ps = ("$ErrorActionPreference='Stop'; Get-CimInstance Win32_Process -ErrorAction Stop | "
          "Where-Object { $_.ProcessId -ne $PID } | "
          "ForEach-Object { ($_.ProcessId, $_.Name, ([string]$_.CommandLine -replace '[\\r\\n\\t]', ' ')) -join [char]9 }")
    try:
        out = subprocess.run(["powershell", "-NoProfile", "-NonInteractive", "-Command", ps], capture_output=True,
                             text=True, timeout=120, encoding="utf-8", errors="replace", check=True,
                             creationflags=0x08000000).stdout
    except (OSError, subprocess.SubprocessError) as exc:
        raise RuntimeError(f"Cannot list running processes: {exc}") from exc
    rows = []
    for line in out.splitlines():
        parts = line.split("\t", 2)
        if len(parts) == 3 and parts[0].strip().isdigit():
            rows.append((int(parts[0]), parts[1].strip(), parts[2]))
    return readable_lines(rows, os.getpid())


def named_by(path: Path, lines: list[str]) -> bool:
    """Does a command line name this exact folder (or something in it)? E:/x also matches Git Bash's /e/x."""
    normalized = str(path).replace("\\", "/").rstrip("/").lower()
    spellings = [re.escape(normalized)]
    drive = re.match(r"([a-z]):/(.*)", normalized)
    if drive:
        spellings.append("/" + drive[1] + "/" + re.escape(drive[2]))
    # A job often names only a sibling output folder (<worktree>-logs, 2026-11-16 townhomes): that is this folder's job.
    pattern = re.compile("(?:" + "|".join(spellings) + r")(?:-(?:" + "|".join(SIBLING_SUFFIXES) + r"))?(?=$|[/\s\"'])")
    return any(pattern.search(line) for line in lines)


def _siblings(path: Path) -> list[Path]:
    """Output folders beside a checkout that belong to its job: <name>-logs, <name>-results and so on."""
    found = [path.with_name(f"{path.name}-{suffix}") for suffix in SIBLING_SUFFIXES]
    return [sibling for sibling in found if sibling.is_dir()]


def _kind(path: Path) -> str:
    marker = path / ".git"
    if marker.is_file():
        return "worktree"
    return "clone" if marker.is_dir() else "plain"


def _git_activity(path: Path) -> float:
    """When this worktree last committed, checked out or rebased (its own HEAD log), 0 if unknown."""
    try:
        text = (path / ".git").read_text(encoding="utf-8", errors="replace").strip()
        gitdir = Path(text[len("gitdir:"):].strip()) if text.startswith("gitdir:") else None
        if gitdir and not gitdir.is_absolute():
            gitdir = path / gitdir
        newest = 0.0
        for name in ("HEAD", "logs/HEAD"):
            target = gitdir / name if gitdir else None
            if target and target.exists():
                newest = max(newest, target.stat().st_mtime)
        return newest
    except OSError:
        return 0.0


def _trim_targets(path: Path, trim_dirs) -> list[Path]:
    found = [path / name for name in trim_dirs]
    plugins = path / "Plugins"
    if plugins.is_dir() and not _reparse(plugins):
        for plugin in plugins.iterdir():
            if plugin.is_dir() and not _reparse(plugin):
                found += [plugin / name for name in ("Intermediate", "Binaries")]
    return [target for target in found if target.is_dir()]


def _trim(path: Path, trim_dirs, dry_run: bool) -> tuple[list[dict], list[str]]:
    """Delete build output git ignores and tracks nothing in. Returns (trimmed, reasons some were left)."""
    trimmed, left = [], []
    for target in _trim_targets(path, trim_dirs):
        relative = target.relative_to(path).as_posix()
        try:
            if _reparse(target) or _has_links(target):
                raise RuntimeError("holds a link")
            if _git(path, "ls-files", "--", relative):
                raise RuntimeError("holds tracked files")
            _git(path, "check-ignore", "-q", relative)   # exit 1 (not ignored) raises
            size = _quick_size(target)
            if not dry_run:
                _remove_tree(target)
                if target.exists():
                    raise RuntimeError("could not be fully removed")
            trimmed.append({"path": str(target), "bytes": size})
        except (RuntimeError, OSError) as exc:
            left.append(f"{relative}: {str(exc)[:120]}")
    return trimmed, left


def _worktree_entry(path: Path) -> dict:
    """This folder's record in its repository's worktree list, plus any other worktree registered inside it."""
    blocks = _git(path, "worktree", "list", "--porcelain").replace("\r", "").split("\n\n")
    mine, inside = None, []
    resolved = path.resolve()
    for block in blocks:
        rows = block.strip().split("\n")
        if not rows or not rows[0].startswith("worktree "):
            continue
        other = Path(rows[0][len("worktree "):]).resolve()
        if other == resolved:
            mine = {"locked": any(row.split(" ", 1)[0] == "locked" for row in rows[1:])}
        elif resolved in other.parents:
            inside.append(str(other))
    if mine is None:
        raise RuntimeError("its repository does not list it as a worktree")
    mine["inside"] = inside
    return mine


def _removable(path: Path) -> str:
    """Raise unless every byte of work in this worktree is provably elsewhere. Returns the branch (or the HEAD)."""
    entry = _worktree_entry(path)
    if entry["locked"]:
        raise RuntimeError("locked worktree")
    if entry["inside"]:
        raise RuntimeError("another worktree lives inside it: " + entry["inside"][0])
    for child in path.iterdir():
        if child.is_dir() and not _reparse(child) and (child / ".git").exists():
            raise RuntimeError(f"another checkout lives inside it: {child.name}")
    if _git(path, "status", "--porcelain=v1", "--untracked-files=all"):
        raise RuntimeError("uncommitted or untracked work")
    if _git(path, "stash", "list") and _kind(path) == "clone":
        raise RuntimeError("stashed work")
    head = _git(path, "rev-parse", "HEAD")
    if not _git(path, "for-each-ref", "--count=1", "--contains", head, "refs/remotes"):
        raise RuntimeError("unpushed commits (HEAD is in no remote branch)")
    ignored = _git(path, "ls-files", "--others", "--ignored", "--exclude-standard", "--directory", "-z")
    for name in ignored.split("\0"):
        parts = Path(name.rstrip("/")).parts if name else ()
        if parts and parts[0] not in DROP_IGNORED and "__pycache__" not in parts and not (
                parts[0] in ("Intermediate", "Binaries", "DerivedDataCache")
                or (len(parts) > 2 and parts[0] == "Plugins" and parts[2] in ("Intermediate", "Binaries"))):
            raise RuntimeError(f"unique ignored files ({name.rstrip('/')[:80]})")
    return _git(path, "branch", "--show-current") or head


def _backup_logs(path: Path, dest: Path) -> int:
    logs = path / "Saved" / "Logs"
    if not logs.is_dir() or _reparse(logs):
        return 0
    files = sorted((f for f in logs.iterdir() if f.is_file() and not f.is_symlink()),
                   key=lambda f: f.stat().st_mtime, reverse=True)
    copied, used = 0, 0
    for f in files:
        size = f.stat().st_size
        if used + size > LOG_BACKUP_BYTES:
            continue
        dest.mkdir(parents=True, exist_ok=True)
        shutil.copy2(_long(f), _long(dest / f.name))
        used += size
        copied += 1
    return copied


def _matches(name: str, patterns) -> bool:
    return any(fnmatch.fnmatch(name.lower(), str(pattern).lower()) for pattern in patterns)


def _candidates(root: Path, keep, disposable, guard) -> list[Path]:
    """Folders directly under the root, and the checkouts one level down inside a plain grouping folder
    (C:\\StoneNode\\wt\\<name>, traffic-mix-1116\\before): the first node pass missed those (2026-11-16)."""
    found = []
    for path in sorted((p for p in root.iterdir() if p.is_dir()), key=lambda p: p.name.lower()):
        try:
            resolved = path.resolve()
            grouping = (not _reparse(path) and _kind(path) == "plain" and not _matches(path.name, keep)
                        and not _matches(path.name, disposable)
                        and not any(g == resolved or resolved in g.parents for g in guard))
            inner = sorted((c for c in path.iterdir() if c.is_dir() and not _reparse(c) and _kind(c) != "plain"),
                           key=lambda p: p.name.lower()) if grouping else []
        except OSError:
            inner = []
        found += inner or [path]
    return found


def retain(roots, keep=(), mode: str = "trim", trim_hours: float = 24.0, remove_days: float = 7.0, disposable=(),
           protected=(), backup_dir: str = "", urgent: bool = False, dry_run: bool = False, sizes: bool = False,
           trim_dirs=TRIM_DIRS, lines=None, now: float | None = None) -> dict:
    """One pass over the folders directly under each root. See the module text for the rules. `keep` and `disposable`
    are folder-name patterns (fnmatch, case-insensitive); `protected` are paths never entered (a folder that is, or
    holds, one is skipped). `lines` are process command lines (tests); by default they are read once per pass."""
    summary = {"checked_at": _now_iso(), "mode": mode, "dry_run": bool(dry_run), "urgent": bool(urgent),
               "freed_bytes": 0, "trimmed": [], "removed": [], "kept": [], "attention": [], "error": ""}
    if mode not in MODES:
        summary["error"] = f"Unknown scratch mode {mode!r}"
        return summary
    if mode == "off" or not roots:
        return summary
    act = mode in ("trim", "remove")
    now = time.time() if now is None else now
    trim_after = min(float(trim_hours), URGENT_TRIM_HOURS) if urgent else float(trim_hours)
    try:
        if lines is None:
            lines = command_lines()
        # The receipt shows what the pass could see: how many command lines, and which folders they name (kept or
        # not), so a pass that is blind to running jobs is visible before it matters.
        summary["processes"], summary["named"] = len(lines), []
        for root in [Path(r) for r in roots if r]:
            try:
                children = [c for c in root.iterdir() if c.is_dir()] if root.is_absolute() and root.is_dir() else []
            except OSError:
                children = []
            summary["named"] += [str(c) for c in children if named_by(c, lines)]
        guard = [Path(p).resolve() for p in protected if p]
        backup_root = Path(backup_dir).resolve() if backup_dir else None
        if backup_root:
            guard.append(backup_root)
        for root in [Path(r) for r in roots if r]:
            if not root.is_absolute() or not root.is_dir():
                summary["kept"].append({"path": str(root), "reason": "Scratch root is missing or not absolute"})
                continue
            if any(_reparse(part) for part in (root, *root.parents) if part.exists() and part != Path(part.anchor)):
                summary["kept"].append({"path": str(root), "reason": "Scratch root is a link"})
                continue
            root = root.resolve()
            for path in _candidates(root, keep, disposable, guard):
                try:
                    entry = {"path": str(path)}
                    if _reparse(path):
                        raise RuntimeError("Link; never entered")
                    if _matches(path.name, keep):
                        raise RuntimeError("On the keep list")
                    resolved = path.resolve()
                    if any(g == resolved or resolved in g.parents for g in guard):
                        raise RuntimeError("Fletchery's own or a protected folder")
                    kind = _kind(path)
                    entry["kind"] = kind
                    is_disposable = kind == "plain" and _matches(path.name, disposable)
                    if kind == "plain" and not is_disposable:
                        raise RuntimeError("Not a git checkout and not a disposable pattern; left alone")
                    # A file time in the future (a clock change, a copied tree) counts as used just now.
                    # A job that writes only to <folder>-results or <folder>-logs is still this folder's job.
                    newest = max([_shallow_newest(path), _git_activity(path) if kind == "worktree" else 0]
                                 + [_shallow_newest(sibling) for sibling in _siblings(path)])
                    idle_hours = max(0.0, now - newest) / 3600
                    entry["idle_hours"] = round(idle_hours, 1)
                    if sizes:
                        entry["bytes"] = _quick_size(path)
                    if idle_hours < trim_after:
                        raise RuntimeError(f"Used {idle_hours:.1f} h ago")
                    if named_by(resolved, lines):
                        raise RuntimeError("A running process names it")
                    old_enough = idle_hours >= float(remove_days) * 24

                    if is_disposable:
                        if not old_enough or mode != "remove":
                            raise RuntimeError(f"Disposable; removed once idle {remove_days:g} days in remove mode")
                        if _has_links(path):
                            raise RuntimeError("Holds a link")
                        size = entry.get("bytes") or _quick_size(path)
                        if not dry_run:
                            _remove_tree(path)
                            if path.exists():
                                raise RuntimeError("Could not be fully removed")
                            summary["freed_bytes"] += size
                        summary["removed"].append({**entry, "bytes": size, "why": "disposable pattern"})
                        continue

                    block = ""
                    if old_enough and kind == "worktree":
                        try:
                            branch = _removable(path)
                        except RuntimeError as exc:
                            block = str(exc)
                        else:
                            if mode == "remove":
                                size = entry.get("bytes") or _quick_size(path)
                                if not dry_run:
                                    if backup_root:
                                        stamp = time.strftime("%Y%m%d-%H%M%S", time.gmtime(now))
                                        entry["logs_backed_up"] = _backup_logs(path, backup_root / f"{path.name}-{stamp}")
                                    if named_by(resolved, command_lines() if os.name == "nt" else lines):
                                        raise RuntimeError("Became busy during cleanup")
                                    common = Path(_git(path, "rev-parse", "--path-format=absolute", "--git-common-dir"))
                                    # No --force: git itself refuses if anything became modified or untracked.
                                    _git(common, "worktree", "remove", str(path))
                                    if path.exists():
                                        raise RuntimeError("Git did not remove the worktree")
                                    summary["freed_bytes"] += size
                                summary["removed"].append({**entry, "bytes": size, "branch": branch,
                                                           "why": "clean and pushed"})
                                continue
                    elif old_enough and kind == "clone":
                        block = "its own clone: trimmed only, never removed"

                    trimmed, left = _trim(path, trim_dirs, dry_run or not act)
                    for item in trimmed:
                        summary["trimmed"].append(item)
                        summary["freed_bytes"] += 0 if (dry_run or not act) else item["bytes"]
                    reason = "Trimmed" if trimmed else "Nothing to trim"
                    if left:
                        reason += "; left " + "; ".join(left[:3])
                    if block:
                        reason += f"; not removed: {block}"
                        if re.search(r"uncommitted|unpushed|stashed|unique ignored", block):
                            summary["attention"].append({**entry, "reason": block})
                    summary["kept"].append({**entry, "reason": reason})
                except Exception as exc:
                    summary["kept"].append({**entry, "reason": str(exc)[:300]})
    except Exception as exc:
        summary["error"] = f"{type(exc).__name__}: {exc}"[:1000]
    return summary


def from_config(get, **extra) -> dict:
    """Run `retain` from profile-style keys (`get("scratchRoots")`, ...): shared by the node worker and the CLI."""
    return retain(get("scratchRoots") or [], keep=get("scratchKeep") or [], mode=str(get("scratchMode") or "trim"),
                  trim_hours=float(get("scratchTrimHours") or 24), remove_days=float(get("scratchRemoveDays") or 7),
                  disposable=get("scratchDisposable") or [], backup_dir=str(get("scratchBackupDir") or ""), **extra)


def main(argv=None) -> int:
    import argparse
    parser = argparse.ArgumentParser(description="Trim and retire idle scratch worktrees. Dry run unless --apply.")
    parser.add_argument("--root", action="append", required=True)
    parser.add_argument("--keep", action="append", default=[], help="folder-name pattern never touched")
    parser.add_argument("--disposable", action="append", default=[], help="plain-folder pattern removed when idle")
    parser.add_argument("--protect", action="append", default=[], help="path never entered")
    parser.add_argument("--mode", choices=MODES[1:], default="trim")
    parser.add_argument("--trim-hours", type=float, default=24)
    parser.add_argument("--remove-days", type=float, default=7)
    parser.add_argument("--backup-dir", default="")
    parser.add_argument("--urgent", action="store_true")
    parser.add_argument("--sizes", action="store_true", help="measure every folder (slow)")
    parser.add_argument("--apply", action="store_true")
    a = parser.parse_args(argv)
    result = retain(a.root, keep=a.keep, mode=a.mode, trim_hours=a.trim_hours, remove_days=a.remove_days,
                    disposable=a.disposable, protected=a.protect, backup_dir=a.backup_dir, urgent=a.urgent,
                    dry_run=not a.apply, sizes=a.sizes)
    json.dump(result, sys.stdout, indent=2)
    print()
    return 1 if result["error"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
